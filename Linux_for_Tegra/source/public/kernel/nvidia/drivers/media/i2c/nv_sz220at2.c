static int sz220at_probe(struct i2c_client *client,
			const struct i2c_device_id *id)
{
	struct device *dev = &client->dev;
	struct device_node *node = dev->of_node;
	struct tegracam_device *tc_dev;
	struct sz220at *priv;
	int err;

	dev_info(dev, "probing v4l2 sensor.\n");
	
	printk("---sz220at_probe 111---\r\n");

	if (!IS_ENABLED(CONFIG_OF) || !node)
		return -EINVAL;

	priv = devm_kzalloc(dev, sizeof(struct sz220at), GFP_KERNEL);
	if (!priv) {
		dev_err(dev, "unable to allocate memory!\n");
		return -ENOMEM;
	}
	tc_dev = devm_kzalloc(dev,
			sizeof(struct tegracam_device), GFP_KERNEL);
	if (!tc_dev)
		return -ENOMEM;
		
	printk("---sz220at_probe 222---\r\n");

	priv->i2c_client = tc_dev->client = client;
	tc_dev->dev = dev;
	strncpy(tc_dev->name, "sz220at", sizeof(tc_dev->name));
	
	tc_dev->dev_regmap_config = &sensor_regmap_config;
	
	tc_dev->sensor_ops = &sz220at_common_ops;
	tc_dev->v4l2sd_internal_ops = &sz220at_subdev_internal_ops;
	tc_dev->tcctrl_ops = &sz220at_ctrl_ops;

	err = tegracam_device_register(tc_dev);
	if (err) {
		dev_err(dev, "tegra camera driver registration failed\n");
		return err;
	}
	
	printk("---sz220at_probe 333---\r\n");

	priv->tc_dev = tc_dev;
	priv->s_data = tc_dev->s_data;
	priv->subdev = &tc_dev->s_data->subdev;

	tegracam_set_privdata(tc_dev, (void *)priv);

	err = sz220at_board_setup(priv);
	if (err) {
		tegracam_device_unregister(tc_dev);
		dev_err(dev, "board setup failed\n");
		return err;
	}
	
	printk("---sz220at_probe 444---\r\n");

	err = sz220at_gmsl_serdes_setup(priv);
	if (err) {
		dev_err(&client->dev,
			"%s gmsl serdes setup failed\n", __func__);
		return err;
	}
	
	printk("---sz220at_probe 555---\r\n");

	err = tegracam_v4l2subdev_register(tc_dev, true);
	if (err) {
		dev_err(dev, "tegra camera subdev registration failed\n");
		return err;
	}
	
	printk("---sz220at_probe 666---\r\n");

	dev_info(&client->dev, "Detected sz220at sensor\n");

	return 0;
}

