static inline int sz220at_read_reg(struct camera_common_data *s_data,
				u16 addr, u16 *val)
{
	int err = 0;
	u32 reg_val = 0;

	err = regmap_read(s_data->regmap, addr, &reg_val);
	*val = reg_val & 0xFFFF;

	return err;
}

static int sz220at_write_reg(struct camera_common_data *s_data,
				u16 addr, u16 val)
{
	int err;
	struct device *dev = s_data->dev;

	err = regmap_write(s_data->regmap, addr, val);
	if (err)
		dev_err(dev, "%s:i2c write failed, 0x%x = %x\n",
			__func__, addr, val);

	return err;
}

int sz220at_write_table(struct tegracam_device *tc_dev, uint8_t *pdata, int32_t setting_size)
{
	int err=0;
	struct device *dev = tc_dev->dev;
	struct sz220at *priv = (struct sz220at *)tegracam_get_privdata(tc_dev);
	struct camera_common_data *s_data = priv->s_data;
	uint8_t i2c_slave;
	uint16_t reg_addr, reg_val, delay;
	u16  reg_val_read =0;
	int32_t i, len;

	for (i = 0; i < setting_size;) 
	{
		len = pdata[i];
		if (len == 5) 
		{
			i2c_slave = pdata[i + 1];
			reg_addr = (pdata[i + 2] << 8) | pdata[i + 3];
			reg_val = (pdata[i + 4] << 8) | pdata[i + 5];
			
			err = sz220at_write_reg(s_data, reg_addr, reg_val);
			if (err) {
				dev_err(dev,"%s: error\n", __func__);
				//return err;
			}	
			
			err = sz220at_read_reg(s_data, reg_addr, &reg_val_read);
			if (err) {
				dev_err(dev,"%s: error\n", __func__);
				//return err;
			}
			else
			{
				if (reg_val_read != reg_val)
				{
					dev_err(dev,"%s: write error reg_addr=0x%x, 0x%x,0x%x\n", __func__, reg_addr, reg_val, reg_val_read);
				}
			}
			
			i = i + len + 1;
			
			//vin_info("write x8b %d@0x%02x: 0x%04x=0x%04x\n", bus, i2c_slave, reg_addr, reg_val);
		} else if (len == 0) 
		{
			delay = pdata[i + 1];
			mdelay(delay);
			i = i + 2;
		}
		else
		{
			dev_err(dev,"%s: wrong data\n", __func__);
			return -1;
		}
	}
	
	return 0;
}

